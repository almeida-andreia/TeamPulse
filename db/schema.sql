    booked_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Concurrency-safe: cancelled rows free the slot but remain confidential history.
CREATE UNIQUE INDEX psychologist_bookings_one_active_slot_idx
    ON private.psychologist_bookings (slot_id) WHERE status = 'booked';

