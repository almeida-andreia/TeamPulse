-- TeamPulse MVP -- PostgreSQL 13+; apply once to an empty application database.
-- This file creates no database roles, grants, policies, or credentials.
-- IMPORTANT: namespaces and ownership links are NOT access control. Before using
-- real data, configure separate Employee/Manager/HR runtime roles. Manager/HR
-- roles must not read wellbeing responses, challenge selections, ownership links,
-- registrations, or bookings. They must use approved aggregate operations only.
-- No dashboard views are exposed here. The later reporting layer must require a
-- configured minimum DISTINCT-respondent threshold (no default is defined here),
-- fail closed when it is absent, and apply complementary/rare-cell suppression
-- consistently to counts, rates, trends, challenge shares, and exports.
-- This is pseudonymized storage: a trusted, restricted operation can reconnect
-- an Employee to their own answers. It is not irreversible anonymization.

BEGIN;

CREATE SCHEMA identity;
CREATE SCHEMA private;
CREATE SCHEMA wellbeing;
CREATE SCHEMA operations;

CREATE TABLE identity.departments (
    department_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- SSO issuer + subject identify an account; no passwords are stored.
CREATE TABLE identity.users (
    user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sso_issuer text NOT NULL CHECK (btrim(sso_issuer) <> ''),
    sso_subject text NOT NULL CHECK (btrim(sso_subject) <> ''),
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    role text NOT NULL CHECK (role IN ('employee', 'manager', 'hr')),
    team_id bigint,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_sso_identity_key UNIQUE (sso_issuer, sso_subject),
    CONSTRAINT users_role_team_check CHECK (
        (role = 'employee' AND team_id IS NOT NULL)
        OR (role IN ('manager', 'hr') AND team_id IS NULL)
    )
);

CREATE TABLE identity.teams (
    team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id bigint NOT NULL REFERENCES identity.departments (department_id),
    name text NOT NULL CHECK (btrim(name) <> ''),
    manager_user_id uuid NOT NULL REFERENCES identity.users (user_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT teams_department_name_key UNIQUE (department_id, name)
);

ALTER TABLE identity.users ADD CONSTRAINT users_team_fkey
    FOREIGN KEY (team_id) REFERENCES identity.teams (team_id);

-- Historical department snapshot. Never derive old department results by joining
-- a response to the team's CURRENT department or an Employee's CURRENT team.
-- Weeks are Monday-based in Europe/Lisbon, with an exclusive next-Monday end.
CREATE TABLE wellbeing.team_weeks (
    team_id bigint NOT NULL REFERENCES identity.teams (team_id),
    week_start date NOT NULL CHECK (extract(isodow FROM week_start) = 1),
    department_id bigint NOT NULL REFERENCES identity.departments (department_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalized_at timestamptz,
    PRIMARY KEY (team_id, week_start),
    CONSTRAINT team_weeks_finalized_at_check CHECK (
        finalized_at IS NULL OR finalized_at >=
        ((week_start + 7)::timestamp AT TIME ZONE 'Europe/Lisbon')
    )
);

-- Intentionally contains NO user_id, SSO subject, email, stable Employee token,
-- IP address, or precise submission timestamp. The random UUID is not derived
-- from identity. Team/week remain quasi-identifiers and need aggregate protection.
-- Approved questionnaire normalization (0..10, one decimal place):
-- Wellbeing: Very positive=10, Positive=7.5, Neutral=5, Struggling=2.5,
-- Very difficult=0. Team connection: Very connected=10, Connected=6.7,
-- Distant=3.3, Disconnected=0; stored as team_integration_score.
-- Workload PRESSURE: Very manageable=0, Manageable=3.3, Difficult=6.7,
-- Very difficult=10. Stress and psychological safety: (1..5 answer - 1) * 2.5.
-- Higher wellbeing, connection and safety are favorable; higher pressure and
-- stress are unfavorable. Safety represents the ease-of-asking-for-help question.
-- Manager Workload Balance = 10 - AVG(workload_score), calculated by reporting;
-- it is not stored. All five measures remain independent, with no combined index.
-- Range checks intentionally allow continuous historical/synthetic scores.
-- The backend must validate and normalize RAW answers before new submissions.
-- These reporting conventions are not clinical assessments or diagnosis.
CREATE TABLE wellbeing.wellbeing_responses (
    response_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    team_id bigint NOT NULL,
    week_start date NOT NULL,
    wellbeing_score numeric(3,1) NOT NULL CHECK (wellbeing_score BETWEEN 0 AND 10),
    workload_score numeric(3,1) NOT NULL CHECK (workload_score BETWEEN 0 AND 10),
    stress_score numeric(3,1) NOT NULL,
    team_integration_score numeric(3,1) NOT NULL CHECK (team_integration_score BETWEEN 0 AND 10),
    psychological_safety_score numeric(3,1) NOT NULL CHECK (psychological_safety_score BETWEEN 0 AND 10),
    comment text CHECK (char_length(comment) <= 2000),
    CONSTRAINT wellbeing_responses_stress_score_check CHECK (stress_score BETWEEN 0 AND 10),
    CONSTRAINT wellbeing_responses_team_week_fkey FOREIGN KEY (team_id, week_start)
        REFERENCES wellbeing.team_weeks (team_id, week_start),
    -- Composite candidate key lets the private link enforce the SAME team/week.
    CONSTRAINT wellbeing_responses_cohort_key UNIQUE (response_id, team_id, week_start)
);

-- PRIVACY-CRITICAL: one eligibility record per Employee/week, including people
-- who do NOT respond. This provides a frozen participation denominator without
-- showing Managers/HR who did or did not participate. response_id is attached only
-- on submission. Employee history traverses this link through an authenticated,
-- Employee-only operation. Never accept an arbitrary caller-supplied user_id.
CREATE TABLE private.employee_weekly_checkins (
    user_id uuid NOT NULL REFERENCES identity.users (user_id),
    week_start date NOT NULL,
    team_id bigint NOT NULL,
    response_id uuid,
    PRIMARY KEY (user_id, week_start),
    CONSTRAINT employee_weekly_checkins_response_key UNIQUE (response_id),
    CONSTRAINT employee_weekly_checkins_team_week_fkey FOREIGN KEY (team_id, week_start)
        REFERENCES wellbeing.team_weeks (team_id, week_start),
    CONSTRAINT employee_weekly_checkins_response_cohort_fkey
        FOREIGN KEY (response_id, team_id, week_start)
        REFERENCES wellbeing.wellbeing_responses (response_id, team_id, week_start)
        DEFERRABLE INITIALLY DEFERRED
);

-- Reciprocal deferred FK: every response MUST have exactly one private owner at
-- commit, not just an optional ownership record. Together with the weekly PK and
-- unique response_id this prevents orphan/extra responses and shared ownership.
-- Submit in ONE transaction: lock eligibility row FOR UPDATE; verify response_id
-- is null; insert response; insert challenge selections; attach response_id; commit.
-- The backend must additionally verify SSO identity and the CURRENT open week.
ALTER TABLE wellbeing.wellbeing_responses
    ADD CONSTRAINT wellbeing_responses_private_owner_fkey
    FOREIGN KEY (response_id)
    REFERENCES private.employee_weekly_checkins (response_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE wellbeing.challenge_factors (
    challenge_factor_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    label text NOT NULL CHECK (btrim(label) <> '')
);

CREATE TABLE wellbeing.response_challenges (
    response_id uuid NOT NULL REFERENCES wellbeing.wellbeing_responses (response_id),
    challenge_factor_id smallint NOT NULL REFERENCES wellbeing.challenge_factors (challenge_factor_id),
    PRIMARY KEY (response_id, challenge_factor_id)
);

CREATE TABLE operations.team_events (
    team_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES identity.teams (team_id),
    event_date date NOT NULL,
    title text NOT NULL CHECK (btrim(title) <> ''),
    created_by_user_id uuid NOT NULL REFERENCES identity.users (user_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One row = one action in a team's plan. The source is an AGGREGATE topic/week,
-- never an individual response. A null source week marks a general team action,
-- with no claim that a measured insight triggered it. No individual answers.
CREATE TABLE operations.team_actions (
    team_action_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL,
    insight_week_start date,
    insight_topic text NOT NULL CHECK (insight_topic IN (
        'wellbeing', 'workload', 'stress', 'team_integration', 'psychological_safety', 'challenge'
    )),
    challenge_factor_id smallint REFERENCES wellbeing.challenge_factors (challenge_factor_id),
    title text NOT NULL CHECK (btrim(title) <> ''),
    -- Legacy plans have no recorded description; new API submissions require it.
    description text CONSTRAINT team_actions_description_check CHECK (description IS NULL OR btrim(description) <> ''),
    owner_user_id uuid NOT NULL REFERENCES identity.users (user_id),
    deadline date NOT NULL,
    status text NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned', 'in_progress', 'completed')),
    created_by_user_id uuid NOT NULL REFERENCES identity.users (user_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT team_actions_source_week_fkey FOREIGN KEY (team_id, insight_week_start)
        REFERENCES wellbeing.team_weeks (team_id, week_start),
    CONSTRAINT team_actions_challenge_check CHECK (
        (insight_topic = 'challenge' AND challenge_factor_id IS NOT NULL)
        OR (insight_topic <> 'challenge' AND challenge_factor_id IS NULL)
    )
);

CREATE TABLE operations.activities (
    -- Existing activities keep NULL scope/source fields. No backfill or new
    -- activity status system: publication and scheduling remain authoritative.
    -- Safe source snapshots are obtained server-side from aggregate reporting.
    department_id bigint REFERENCES identity.departments (department_id),
    related_area text CHECK (related_area IN ('wellbeing', 'workloadBalance', 'teamIntegration', 'psychologicalSafety', 'stress')),
    source_week_start date,
    source_value numeric(3,1),
    source_change numeric(3,1),
    CONSTRAINT activities_insight_source_check CHECK (
        (source_week_start IS NULL AND source_value IS NULL AND source_change IS NULL)
        OR (department_id IS NOT NULL AND related_area IS NOT NULL AND source_week_start IS NOT NULL
            AND extract(isodow FROM source_week_start) = 1
            AND source_value IS NOT NULL AND source_value BETWEEN 0 AND 10
            AND source_change IS NOT NULL AND source_change BETWEEN -10 AND 10
            AND ((related_area = 'stress' AND source_change > 0) OR (related_area <> 'stress' AND source_change < 0)))
    ),
    activity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL CHECK (btrim(description) <> ''),
    activity_type text NOT NULL CHECK (btrim(activity_type) <> ''),
    starts_at timestamptz NOT NULL,
    duration_minutes integer NOT NULL CHECK (duration_minutes > 0),
    format text NOT NULL CHECK (format IN ('online', 'in_person')),
    target_audience text NOT NULL CHECK (btrim(target_audience) <> ''),
    is_featured boolean NOT NULL DEFAULT false,
    published_at timestamptz,
    created_by_user_id uuid NOT NULL REFERENCES identity.users (user_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT activities_publication_check CHECK (
        published_at IS NULL OR published_at <= starts_at
    )
);

-- Support participation can itself be sensitive. No Manager/HR attendee-list
-- access is implied by the ability to publish an activity.
CREATE TABLE private.activity_registrations (
    activity_id bigint NOT NULL REFERENCES operations.activities (activity_id),
    user_id uuid NOT NULL REFERENCES identity.users (user_id),
    registered_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (activity_id, user_id)
);

-- Optional US4: providers are not a fourth application role. No clinical records.
CREATE TABLE operations.psychologists (
    psychologist_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE operations.psychologist_slots (
    slot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    psychologist_id bigint NOT NULL REFERENCES operations.psychologists (psychologist_id),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    format text NOT NULL,
    location text,
    video_url text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT psychologist_slots_provider_start_key UNIQUE (psychologist_id, starts_at),
    CONSTRAINT psychologist_slots_time_check CHECK (ends_at > starts_at),
    -- Built-in range GiST operators avoid an extension dependency. The closed
    -- numeric point [provider, provider] overlaps only for the SAME provider.
    -- Combined with [start, end), this rejects overlapping slots atomically,
    -- including concurrent inserts, while allowing adjacent appointments.
    CONSTRAINT psychologist_slots_no_overlap EXCLUDE USING gist (
        numrange(psychologist_id::numeric, psychologist_id::numeric, '[]') WITH &&,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ),
    CONSTRAINT psychologist_slots_format_check CHECK (
        (format = 'online' AND video_url IS NOT NULL
            AND btrim(video_url) <> '' AND location IS NULL)
        OR (format = 'in_person' AND location IS NOT NULL
            AND btrim(location) <> '' AND video_url IS NULL)
    )
);

-- Independent of wellbeing responses: no response FK or check-in-based eligibility.
-- Only the booking owner may retrieve confirmation details/video links once the
-- access layer is configured. Public availability must omit booking identities.
CREATE TABLE private.psychologist_bookings (
    booking_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
