-- All helpers are SECURITY INVOKER: no privilege escalation or access grants.
-- Role checks validate stored relationships, NOT the identity of the SQL caller.
-- Actual caller authorization must be configured separately before real use.
CREATE FUNCTION identity.protect_user_role() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF NEW.role IS DISTINCT FROM OLD.role THEN
        RAISE EXCEPTION 'Account roles are fixed in the MVP; role reassignment requires controlled maintenance';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER users_protect_role BEFORE UPDATE OF role ON identity.users
    FOR EACH ROW EXECUTE FUNCTION identity.protect_user_role();

CREATE FUNCTION identity.validate_team_manager() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    PERFORM 1 FROM identity.users
        WHERE user_id = NEW.manager_user_id AND role = 'manager';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'A team manager must have the Manager role';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER teams_validate_manager BEFORE INSERT OR UPDATE OF manager_user_id ON identity.teams
    FOR EACH ROW EXECUTE FUNCTION identity.validate_team_manager();

CREATE FUNCTION wellbeing.protect_team_week() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Historical team weeks cannot be deleted through ordinary writes';
    ELSIF TG_OP = 'INSERT' THEN
        PERFORM 1 FROM identity.teams
            WHERE team_id = NEW.team_id AND department_id = NEW.department_id FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'A new cohort must snapshot the team department';
        END IF;
    ELSE
        IF ROW(NEW.team_id, NEW.week_start, NEW.department_id, NEW.created_at)
            IS DISTINCT FROM ROW(OLD.team_id, OLD.week_start, OLD.department_id, OLD.created_at)
            OR OLD.finalized_at IS NOT NULL THEN
            RAISE EXCEPTION 'Historical cohort fields and finalized weeks are immutable';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER team_weeks_protect_history BEFORE INSERT OR UPDATE OR DELETE ON wellbeing.team_weeks
    FOR EACH ROW EXECUTE FUNCTION wellbeing.protect_team_week();

CREATE FUNCTION private.protect_weekly_checkin() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Weekly eligibility and ownership records cannot be deleted through ordinary writes';
    ELSIF TG_OP = 'INSERT' THEN
        -- Snapshot the Employee's team at enrollment, not at history retrieval.
        PERFORM 1 FROM identity.users WHERE user_id = NEW.user_id
            AND role = 'employee' AND is_active AND team_id = NEW.team_id FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Weekly eligibility must snapshot an active Employee in their current team';
        END IF;
    ELSIF ROW(NEW.user_id, NEW.week_start, NEW.team_id)
            IS DISTINCT FROM ROW(OLD.user_id, OLD.week_start, OLD.team_id)
        OR (OLD.response_id IS NOT NULL AND NEW.response_id IS DISTINCT FROM OLD.response_id) THEN
        RAISE EXCEPTION 'Weekly membership is immutable and a submitted response cannot be replaced or cleared';
    END IF;

    -- FOR SHARE serializes submission/enrollment with cohort finalization.
    PERFORM 1 FROM wellbeing.team_weeks WHERE team_id = NEW.team_id
        AND week_start = NEW.week_start AND finalized_at IS NULL FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Weekly eligibility and submissions require an open cohort';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER employee_weekly_checkins_protect_history
    BEFORE INSERT OR UPDATE OR DELETE ON private.employee_weekly_checkins
    FOR EACH ROW EXECUTE FUNCTION private.protect_weekly_checkin();

CREATE FUNCTION wellbeing.protect_response() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Submitted wellbeing answers cannot be edited or deleted through ordinary writes';
    END IF;
    PERFORM 1 FROM wellbeing.team_weeks WHERE team_id = NEW.team_id
        AND week_start = NEW.week_start AND finalized_at IS NULL FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Responses require an open reporting cohort';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER wellbeing_responses_protect_history
    BEFORE INSERT OR UPDATE OR DELETE ON wellbeing.wellbeing_responses
    FOR EACH ROW EXECUTE FUNCTION wellbeing.protect_response();

CREATE FUNCTION wellbeing.protect_response_challenges() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    checked_response_id uuid;
BEGIN
    IF TG_OP = 'DELETE' THEN
        checked_response_id := OLD.response_id;
    ELSE
        checked_response_id := NEW.response_id;
    END IF;
    IF EXISTS (SELECT 1 FROM private.employee_weekly_checkins WHERE response_id = checked_response_id)
        OR (TG_OP = 'UPDATE' AND NEW.response_id IS DISTINCT FROM OLD.response_id) THEN
        RAISE EXCEPTION 'Challenge selections must be saved before attaching the response to its owner';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER response_challenges_protect_history
    BEFORE INSERT OR UPDATE OR DELETE ON wellbeing.response_challenges
    FOR EACH ROW EXECUTE FUNCTION wellbeing.protect_response_challenges();

CREATE FUNCTION operations.validate_team_record() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    source_changed boolean := TG_OP = 'INSERT';
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM 1 FROM identity.teams WHERE team_id = NEW.team_id
            AND manager_user_id = NEW.created_by_user_id FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Team records must be created by the assigned Manager';
        END IF;
    ELSE
        IF NEW.team_id IS DISTINCT FROM OLD.team_id
            OR NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id THEN
            RAISE EXCEPTION 'Team record scope and creator cannot be reassigned';
        END IF;
    END IF;

    IF TG_TABLE_NAME = 'team_actions' THEN
        PERFORM 1 FROM identity.users u
            WHERE u.user_id = NEW.owner_user_id
            AND (u.role = 'hr' OR (u.role = 'employee' AND u.team_id = NEW.team_id)
                OR (u.role = 'manager' AND EXISTS (
                    SELECT 1 FROM identity.teams t WHERE t.team_id = NEW.team_id
                    AND t.manager_user_id = u.user_id))) FOR SHARE OF u;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'An action owner must belong to its team, manage it, or have the HR role';
        END IF;
        IF TG_OP = 'UPDATE' THEN
            source_changed := ROW(NEW.insight_week_start, NEW.insight_topic, NEW.challenge_factor_id)
                IS DISTINCT FROM ROW(OLD.insight_week_start, OLD.insight_topic, OLD.challenge_factor_id);
            NEW.updated_at := CURRENT_TIMESTAMP;
        END IF;
        IF source_changed AND NEW.insight_week_start IS NOT NULL THEN
            PERFORM 1 FROM wellbeing.team_weeks WHERE team_id = NEW.team_id
                AND week_start = NEW.insight_week_start AND finalized_at IS NOT NULL;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Actions must reference a finalized reporting week';
            END IF;
        END IF;
        -- Finalized does not mean privacy-safe: later action-creation operations
        -- must also verify that the source insight passes configured suppression.
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER team_events_validate BEFORE INSERT OR UPDATE ON operations.team_events
    FOR EACH ROW EXECUTE FUNCTION operations.validate_team_record();
CREATE TRIGGER team_actions_validate BEFORE INSERT OR UPDATE ON operations.team_actions
    FOR EACH ROW EXECUTE FUNCTION operations.validate_team_record();

CREATE FUNCTION operations.validate_activity() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    PERFORM 1 FROM identity.users WHERE user_id = NEW.created_by_user_id AND role = 'hr';
    IF NOT FOUND THEN RAISE EXCEPTION 'Activity creators must have the HR role'; END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id THEN
            RAISE EXCEPTION 'An activity creator cannot be reassigned';
        END IF;
        IF ROW(NEW.source_week_start, NEW.source_value, NEW.source_change)
            IS DISTINCT FROM ROW(OLD.source_week_start, OLD.source_value, OLD.source_change)
            OR (OLD.source_week_start IS NOT NULL AND ROW(NEW.department_id, NEW.related_area)
                IS DISTINCT FROM ROW(OLD.department_id, OLD.related_area)) THEN
            RAISE EXCEPTION 'An activity aggregate source cannot be reassigned';
        END IF;
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER activities_validate BEFORE INSERT OR UPDATE ON operations.activities
    FOR EACH ROW EXECUTE FUNCTION operations.validate_activity();

CREATE FUNCTION private.validate_activity_registration() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    PERFORM 1 FROM identity.users WHERE user_id = NEW.user_id AND role = 'employee' AND is_active;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Activity registrations require an active Employee';
    END IF;
    PERFORM 1 FROM operations.activities WHERE activity_id = NEW.activity_id
        AND published_at IS NOT NULL AND published_at <= NEW.registered_at FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Employees can register only for already published activities';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER activity_registrations_validate BEFORE INSERT OR UPDATE ON private.activity_registrations
    FOR EACH ROW EXECUTE FUNCTION private.validate_activity_registration();

CREATE FUNCTION operations.validate_psychologist_slot() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.slot_id IS DISTINCT FROM OLD.slot_id
            OR NEW.psychologist_id IS DISTINCT FROM OLD.psychologist_id THEN
            RAISE EXCEPTION 'Slot identity and provider cannot be reassigned';
        END IF;
        IF ROW(NEW.starts_at, NEW.ends_at, NEW.format, NEW.location, NEW.video_url)
            IS DISTINCT FROM ROW(OLD.starts_at, OLD.ends_at, OLD.format, OLD.location, OLD.video_url)
            AND EXISTS (SELECT 1 FROM private.psychologist_bookings WHERE slot_id = OLD.slot_id) THEN
            RAISE EXCEPTION 'A slot with booking history cannot be changed; reschedule the booking instead';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER psychologist_slots_validate BEFORE INSERT OR UPDATE ON operations.psychologist_slots
    FOR EACH ROW EXECUTE FUNCTION operations.validate_psychologist_slot();

CREATE FUNCTION private.validate_psychologist_booking() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    session_start timestamptz;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Cancel bookings instead of deleting confidential booking history';
    END IF;
    PERFORM 1 FROM identity.users WHERE user_id = NEW.user_id AND role = 'employee' AND is_active;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Psychologist bookings require an active Employee';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF ROW(NEW.booking_id, NEW.user_id, NEW.booked_at)
            IS DISTINCT FROM ROW(OLD.booking_id, OLD.user_id, OLD.booked_at) THEN
            RAISE EXCEPTION 'Booking identity, owner, and original booking time are immutable';
        END IF;
        IF ROW(NEW.slot_id, NEW.status) IS DISTINCT FROM ROW(OLD.slot_id, OLD.status) THEN
            IF OLD.status = 'cancelled' THEN
                RAISE EXCEPTION 'A cancelled booking cannot be reactivated; create a new booking';
            END IF;
            SELECT starts_at INTO session_start FROM operations.psychologist_slots
                WHERE slot_id = OLD.slot_id FOR SHARE;
            IF clock_timestamp() > session_start - interval '2 hours' THEN
                RAISE EXCEPTION 'Cancellation or rescheduling requires at least two hours notice';
            END IF;
            IF NEW.status = 'cancelled' AND NEW.slot_id <> OLD.slot_id THEN
                RAISE EXCEPTION 'Cancellation cannot also change the slot';
            END IF;
        END IF;
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;
    IF TG_OP = 'INSERT' AND NEW.status <> 'booked' THEN
        RAISE EXCEPTION 'New bookings must start with booked status';
    END IF;
    IF NEW.status = 'booked' THEN
        SELECT starts_at INTO session_start FROM operations.psychologist_slots
            WHERE slot_id = NEW.slot_id FOR SHARE;
        IF NOT FOUND OR session_start <= clock_timestamp() THEN
            RAISE EXCEPTION 'Booking requires a future available slot';
        END IF;
    END IF;
    -- The partial unique index, rather than a race-prone availability SELECT,
    -- decides whether another active booking already occupies this slot.
    RETURN NEW;
END;
$$;

CREATE TRIGGER psychologist_bookings_validate
    BEFORE INSERT OR UPDATE OR DELETE ON private.psychologist_bookings
    FOR EACH ROW EXECUTE FUNCTION private.validate_psychologist_booking();

